import { chromium } from 'playwright';
import fs from 'node:fs';
fs.mkdirSync('test-results', { recursive: true });
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.on('console', message => { if (message.type() === 'error' || message.type() === 'warning') console.log(message.type(), message.text().slice(0, 450)); });
page.on('pageerror', error => console.log('PAGE ERROR', error.message));
await page.goto('http://127.0.0.1:3001');
await page.getByPlaceholder('Find a game…').fill('Sonic the Hedgehog 2');
await page.waitForTimeout(3000);
console.log('ROWS', await page.locator('.game-row').allTextContents());
await page.locator('.game-row').first().click();
await page.screenshot({ path: 'test-results/library.png', fullPage: true });
await page.getByRole('button', { name: 'Try this game' }).click();
await page.waitForTimeout(12000);
console.log('PHASE', await page.locator('.screen').getAttribute('data-phase'));
console.log('ERROR', await page.locator('[role=alert]').allTextContents());
console.log('FRAMES', page.frames().map(f => f.url()));
await page.screenshot({ path: 'test-results/playback.png', fullPage: true });
await page.getByRole('button', { name: 'Finish session' }).click();
await browser.close();
